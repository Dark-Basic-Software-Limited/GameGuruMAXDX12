			case 1: fResult = WickedCall_GetObjectAlpha (pObject); break;
			case 2: fResult = WickedCall_GetObjectAlphaRef (pObject) * 100.0f; break;
			case 3: fResult = WickedCall_GetObjectNormalness (pObject) * 100.0f; break;
