// 2 = force it opaque and override the texture with a flat colour
int gg_objpreview_backdrop = 1;
// ★ The preview owns its lighting. A point light's illuminance falls as 1/d^2 and the
// framing distance scales with the object (fCamMove = fLargest * ~3.5, anything from ~50
// to ~8750 units), so a FIXED intensity cannot work across the library - the shipped
// thumb lights are 8 candela with a 2900 range, which is a fraction of a lux on a small
// prop and entirely out of range on a large one. Scale both with the distance instead.
// k is the illuminance the key light lands on the subject: intensity = k * d^2, so the same k
// frames a 15-unit prop and a 2500-unit building identically.
//
// ★ MATCHED TO THE DX11 REFERENCE, and the statistic is the whole story. The shipped static
// thumbnails were generated by DX11, so one of them sitting in the same grid IS the reference -
// but comparing on MEAN cell luminance says a correct preview and a blown one are identical
// (66.8 vs 67.6 on Lee's two screenshots), because the backdrop plane fills most of the cell and
// swamps the subject. p99 - the brightest 1%, which is the lit side of the subject - told the
// truth: 145.6 reference against 220.1 live.
//
// Measured in-session against the static thumbnail in the same cell at the same resolution
// (tools/objpreview_match_dx11.sh), reference p99 150.3:
//     k = 0.00008 -> 132.5     k = 0.00025 -> 183.1     k = 0.00060 -> 223.9
//     k = 0.00015 -> 155.4     k = 0.00040 -> 208.2
// 0.00013 interpolates onto the reference.
//
// ⚠ The response saturates HARD at the top: above k ~0.01 every value is pixel-identical, so a
// sweep that starts too high reads as a dead knob. It cost a whole run reading a flat line as
// 'the override is not being applied'.
//
// ⚠⚠⚠ SUPERSEDED 3.97 - THE k*d^2 MODEL WAS WRONG FOR THIS ENGINE, AND IT TURNED A BUILDING WHITE.
// It assumed a point light falls off as 1/d^2. This fork does not: 2.10 put the DX11 falloff
// back, energy * (1 - d^2/r^2)^2 with NO inverse-square term (lightingHF.hlsli
// attenuation_pointlight, OPTION_BIT_GG_DX11_LIGHT_FALLOFF). With the range scaled to 6d the window
// term is ~0.92 at every size, so the light a subject receives IS the intensity - and k*d^2 made
// it grow with the square of the object's size. A building framed at d = 1677 got 365 units and
// every face saturated; a small prop at d = 60 got 0.47. One object calibrated, the rest of the
// library wrong in both directions. ★ A calibration is only as general as the physics it
// assumes - check the falloff before fitting a constant to a single object.
//
// Now: a FIXED intensity (the window term does the only distance work there is to do). lightk is
// kept as an experiment knob - >0 brings the old k*d^2 back.
float gg_objpreview_lightk = 0.0f;     // >0 = old k*d^2 model (experiments only)
float gg_objpreview_lightint = 4.0f;   // key light energy, DX11 units; fill is 0.45 of this

